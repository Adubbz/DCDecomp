#!/usr/bin/env python3
"""Write a release's split configuration from its own disc.

    splat_config.py                 write the symbol lists; for a release other
                                    than NTSC also the yaml, the linker script
                                    and the fixups, where they do not exist yet
    splat_config.py --overwrite     write those three even where they exist
    splat_config.py --check         compare instead of writing

The release is the one DCDECOMP_REGION names (scripts/build/region.py).

A symbol list is retail's own symbol table, read out of the release's
executable, and is regenerated whenever the tool runs. What no symbol table
records -- where each translation unit starts, the linker script and the object
fixups -- is NTSC 1.02's checked-in configuration carried over: each NTSC
address is moved to the address the same thing has in this release, found by
symbol name, and for the compiler's unnamed constants by pairing the
relocations of the functions and data both releases share. Once written, the
carried files are maintained by hand like NTSC's.

Carried over onto NTSC itself every address stays where it is, so `--check`
with the default region compares the symbol lists and proves the carry by
reproducing NTSC's own yaml and linker script exactly.
"""

import argparse
import bisect
import difflib
import hashlib
import json
import os
import re
import struct
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import region  # noqa: E402

IMAGES = ("main", "title", "dun")
BASENAME = "SCUS_971.11"
OVERLAY_FILES = {"title": "TITLE.BIN", "dun": "DUN.BIN"}
MAIN_FILE_OFFSET = 0x100

HEADER = ["// Retail's own symbol table.",
          "// Generated by scripts/build/splat_config.py; do not edit.", ""]
SKIP_NAMES = {"gcc2_compiled.", "__gnu_compiled_c", "__gnu_compiled_cplusplus",
              "__bss_end", "_end", "end", "_stack"}
TRUNCATED = {"SetClut__FP13sceVif1PacketP8CTextureP1":
             "SetClut__FP13sceVif1PacketP8CTextureP1i"}
STATIC_INIT = {"main": ("__static_init", "__static_init_end", "RO_"),
               "title": ("_title_static_init", "_title_static_init_end", "D_"),
               "dun": ("_dun_static_init", "_dun_static_init_end", "D_")}

SHT_REL, SHT_SYMTAB = 9, 2
STT_NOTYPE, STT_OBJECT, STT_FUNC = 0, 1, 2


class Retail:
    """One release's executable and overlays, as its symbol table describes them."""

    def __init__(self, name):
        self.name = name
        self.info = dict(region.REGIONS[name], **region.paths(name))
        root = Path(self.info["extracted_iso"])
        self.elf_path = root / BASENAME
        data = self.elf_path.read_bytes()
        shoff, = struct.unpack_from("<I", data, 0x20)
        shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x2E)
        sections = []
        for i in range(shnum):
            fields = struct.unpack_from("<10I", data, shoff + i * shentsize)
            sections.append(dict(zip(("name", "type", "flags", "addr", "offset", "size",
                                      "link", "info", "align", "entsize"), fields)))
        names = sections[shstrndx]["offset"]
        for s in sections:
            s["name"] = data[names + s["name"]:data.index(b"\0", names + s["name"])].decode()
        self.shndx = {s["name"]: i for i, s in enumerate(sections)}
        symtab = next(s for s in sections if s["type"] == SHT_SYMTAB)
        strtab = sections[symtab["link"]]["offset"]
        self.syms = []
        for k in range(symtab["size"] // 16):
            name, value, size, info, other, shndx = struct.unpack_from(
                "<IIIBBH", data, symtab["offset"] + k * 16)
            text = data[strtab + name:data.index(b"\0", strtab + name)].decode("latin1")
            self.syms.append(dict(idx=k, name=text, value=value, size=size,
                                  type=info & 15, shndx=shndx))
        self.rel = {}
        for s in sections:
            if s["type"] != SHT_REL:
                continue
            rows = defaultdict(list)
            for k in range(s["size"] // 8):
                offset, info = struct.unpack_from("<II", data, s["offset"] + k * 8)
                sym = self.syms[info >> 8]
                rows[offset].append((info & 0xFF, sym["name"], sym["value"]))
            self.rel[sections[s["info"]]["name"]] = rows
        main = sections[self.shndx["main"]]
        self.images = {"main": (main["addr"], data[main["offset"]:main["offset"] + main["size"]])}
        for image, file in OVERLAY_FILES.items():
            blob = (root / file).read_bytes()
            self.images[image] = (struct.unpack_from("<I", blob, 8)[0], blob)
        reginfo = sections[self.shndx[".reginfo"]]
        self.gp, = struct.unpack_from("<I", data, reginfo["offset"] + 0x14)
        self.sections = self.info["sections"]

    def image_range(self, image):
        return self.sections[image][0][2], self.sections[image][-1][3]

    def image_of(self, sym):
        if sym["shndx"] == self.shndx.get("heap"):
            return "main"
        for image in IMAGES:
            if sym["shndx"] == self.shndx[image]:
                return image
        return None

    def file_end(self, image):
        """The address the image's file stops at: .bss and .sbss take no bytes."""
        base, blob = self.images[image]
        if image == "main":
            return next(start for name, _k, start, _e in self.sections["main"] if name == ".sbss")
        return base + len(blob)

    def offset(self, image, address):
        if image == "main":
            return address - self.sections["main"][0][2] + MAIN_FILE_OFFSET
        return address - self.images[image][0]

    def address(self, image, offset):
        if image == "main":
            return offset - MAIN_FILE_OFFSET + self.sections["main"][0][2]
        return offset + self.images[image][0]

    def functions(self, image):
        seen, out = set(), []
        for s in sorted(self.syms, key=lambda s: (s["value"], s["name"])):
            if (s["type"] == STT_FUNC and s["size"] and s["shndx"] == self.shndx[image]
                    and (s["value"], s["name"]) not in seen):
                seen.add((s["value"], s["name"]))
                out.append(s)
        return out

    def target_path(self, image):
        return f"{self.info['extracted_iso']}/{OVERLAY_FILES.get(image, BASENAME)}"


def normalize(name):
    name = name.replace(",", "_").replace("<", "_").replace(">", "_")
    return re.sub(r"\.(?=[0-9])", "_", name)


def spelled(retail):
    """{symbol index: the name the configuration writes for it}."""
    seen, out = Counter(), {}
    for s in retail.syms:
        if not s["name"]:
            continue
        name = normalize(s["name"])
        seen[name.lower()] += 1
        count = seen[name.lower()]
        name = name if count == 1 else f"{name}__{count}"
        out[s["idx"]] = TRUNCATED.get(name, name)
    return out


def listed(sym):
    name = sym["name"]
    if not name or sym["type"] not in (STT_NOTYPE, STT_OBJECT, STT_FUNC):
        return False
    if sym["value"] < 0x100000 or name in SKIP_NAMES or name.startswith("."):
        return False
    return not re.fullmatch(r"_\w+_size", name)


def attributes(sym_type, size, own):
    if own:
        if sym_type == STT_FUNC:
            return f"type:func size:{size:#x} allow_duplicated:True"
        return f"size:{size:#x} allow_duplicated:True" if size else "allow_duplicated:True"
    if sym_type == STT_FUNC:
        return f"type:func allow_duplicated:True size:{size:#x} absolute:True"
    if size:
        return f"allow_duplicated:True size:{size:#x} absolute:True"
    return "allow_duplicated:True absolute:True"


def symbol_list(retail, image):
    names = spelled(retail)
    foreign = ("title", "dun") if image == "main" else ("main",)
    lo, hi = retail.image_range(image)
    at = defaultdict(set)
    for s in retail.syms:
        if s["name"] and s["type"] in (STT_NOTYPE, STT_OBJECT, STT_FUNC):
            at[s["value"]].add(retail.image_of(s))
    rows = []
    for s in retail.syms:
        if not listed(s):
            continue
        owner, value = retail.image_of(s), s["value"]
        if owner == image:
            if lo <= value < hi:
                own = True
            elif at[value] - {image}:
                continue
            else:
                own = False
        elif owner in foreign:
            olo, ohi = retail.image_range(owner)
            if image in at[value] or not olo <= value < ohi:
                continue
            own = False
        else:
            continue
        rows.append((value, s["type"] != STT_FUNC, names[s["idx"]],
                     attributes(s["type"], s["size"], own)))
    for owner in (image,) + foreign:
        first, last, prefix = STATIC_INIT[owner]
        bounds = {s["name"]: s["value"] for s in retail.syms if s["name"] in (first, last)}
        if len(bounds) == 2:
            for address in range(bounds[first], bounds[last], 4):
                rows.append((address, True, f"{prefix}{address:08X}",
                             attributes(STT_OBJECT, 4, owner == image)))
    rows.sort(key=lambda r: r[:3])
    return "\n".join(HEADER + [f"{n} = 0x{a:08x}; // {at}" for a, _t, n, at in rows]) + "\n"


class Carry:
    """Where each NTSC address went in another release."""

    def __init__(self, source, target):
        self.source, self.target = source, target
        self.functions = {image: self._functions(image) for image in IMAGES}
        self.data = {image: self._data(image) for image in IMAGES}
        self.keys = {image: sorted(self.data[image]) for image in IMAGES}
        self.anchors = {image: self._anchors(image) for image in IMAGES}
        self.target_names = spelled(target)
        self.source_names = spelled(source)

    def _functions(self, image):
        a, b = defaultdict(list), defaultdict(list)
        for f in self.source.functions(image):
            a[f["name"]].append(f["value"])
        for f in self.target.functions(image):
            b[f["name"]].append(f["value"])
        out = {}
        for name, values in a.items():
            for x, y in zip(sorted(values), sorted(b.get(name, []))):
                out[x] = y
        return out

    def _named(self, retail, image, pred):
        out = defaultdict(list)
        for s in retail.syms:
            if s["shndx"] == retail.shndx[image] and s["name"] and pred(s):
                section = next((n for n, _k, lo, hi in retail.sections[image]
                                if lo <= s["value"] < hi), None)
                out[(s["name"], section)].append(s)
        for values in out.values():
            values.sort(key=lambda s: s["value"])
        return out

    def _relocations(self, retail, image, lo, hi):
        rows = retail.rel.get(image, {})
        out = []
        for address in range(lo & ~3, hi, 4):
            for kind, name, value in rows.get(address, ()):
                label = "@" if re.fullmatch(r"@\d+", name) else re.sub(r"\$\d+$", "$", name)
                out.append((kind, label, value))
        return out

    def _data(self, image):
        votes = defaultdict(Counter)
        def plain(s):
            return (s["type"] in (STT_NOTYPE, STT_OBJECT, STT_FUNC)
                    and not s["name"].startswith((".", "@")))
        a = self._named(self.source, image, plain)
        b = self._named(self.target, image, plain)
        for name, values in a.items():
            for x, y in zip(values, b.get(name, [])):
                votes[x["value"]][y["value"]] += 100
        def sized(s):
            return s["type"] in (STT_OBJECT, STT_FUNC) and s["size"] and not s["name"].startswith("@")
        a = self._named(self.source, image, sized)
        b = self._named(self.target, image, sized)
        for name, values in a.items():
            for x, y in zip(values, b.get(name, [])):
                ra = self._relocations(self.source, image, x["value"], x["value"] + x["size"])
                rb = self._relocations(self.target, image, y["value"], y["value"] + y["size"])
                matcher = difflib.SequenceMatcher(None, [r[:2] for r in ra], [r[:2] for r in rb],
                                                  autojunk=False)
                for op, i1, i2, j1, j2 in matcher.get_opcodes():
                    if op == "equal":
                        for i, j in zip(range(i1, i2), range(j1, j2)):
                            if ra[i][2] and rb[j][2]:
                                votes[ra[i][2]][rb[j][2]] += 1
        def section(retail, address):
            return next((n for n, _k, lo, hi in retail.sections[image] if lo <= address < hi), None)
        out = {}
        for x, c in votes.items():
            for y, _count in c.most_common():
                if section(self.source, x) == section(self.target, y):
                    out[x] = y
                    break
        return out

    def _anchors(self, image):
        out = {}
        for (_n, _k, a0, a1), (_m, _l, b0, b1) in zip(self.source.sections[image],
                                                      self.target.sections[image]):
            out[a0], out[a1] = b0, b1
        out[self.source.file_end(image)] = self.target.file_end(image)
        return out

    def _at(self, retail, image, address):
        return [s for s in retail.syms
                if s["value"] == address and s["shndx"] == retail.shndx[image] and s["name"]]

    def text(self, image, address):
        if address in self.anchors[image]:
            return self.anchors[image][address]
        return self.functions[image].get(address)

    def datum(self, image, address):
        if address in self.anchors[image]:
            return self.anchors[image][address]
        if address in self.data[image]:
            return self.data[image][address]
        if address in self.functions[image]:
            return self.functions[image][address]
        keys, data = self.keys[image], self.data[image]
        i = bisect.bisect_left(keys, address)
        deltas = []
        if i > 0:
            deltas.append(data[keys[i - 1]] - keys[i - 1])
        if i < len(keys):
            deltas.append(data[keys[i]] - keys[i])
        if len(set(deltas)) == 1:
            return address + deltas[0]
        for s in self.source.syms:
            if (s["size"] and s["value"] + s["size"] == address and s["value"] in data
                    and s["shndx"] == self.source.shndx[image]):
                for t in self._at(self.target, image, data[s["value"]]):
                    if t["size"] and t["type"] == s["type"]:
                        return t["value"] + t["size"]
        wanted = [(s["size"], "@" if s["name"].startswith("@") else s["name"])
                  for s in self._at(self.source, image, address)]
        for delta in deltas:
            found = [(s["size"], "@" if s["name"].startswith("@") else s["name"])
                     for s in self._at(self.target, image, address + delta)]
            if wanted and any(w in found for w in wanted):
                return address + delta
        return None

    def name(self, image, retail_name):
        """The target's spelling of the symbol NTSC's configuration calls `retail_name`."""
        for s in self.source.syms:
            if self.source_names.get(s["idx"]) != retail_name:
                continue
            owner = self.source.image_of(s) or image
            moved = (self.text(owner, s["value"]) if s["type"] == STT_FUNC
                     else self.datum(owner, s["value"]))
            if moved is None:
                return None
            invented = retail_name.startswith("@")
            for t in self.target.syms:
                if (t["value"] == moved and self.target.image_of(t) == owner
                        and t["name"].startswith("@") == invented and t["type"] == s["type"]):
                    return self.target_names[t["idx"]]
            return None
        return retail_name


def hex_like(token, value):
    digits = len(token) - 2
    return ("0x%0*X" if any(c.isupper() for c in token[2:]) else "0x%0*x") % (digits, value)


YAML_SUB = re.compile(r"^(\s*-\s*\{start:\s*)(0x[0-9a-fA-F]+)(,\s*type:\s*([^,}\s]+),\s*name:\s*([^,}\s]+).*)$")
YAML_VRAM = re.compile(r"(vram:\s*)(0x[0-9a-fA-F]+)")
YAML_END = re.compile(r"^(\s*-\s*\[)(0x[0-9a-fA-F]+)(\]\s*)$")
UNIT_KINDS = ("cpp", "c", "asmtu", "asm")


def carry_yaml(carry, image, text, problems):
    source, target = carry.source, carry.target
    config = target.info["config"]
    base = os.path.relpath(".", config)
    build = target.info["build"]
    fields = {
        "sha1": hashlib.sha1(Path(target.target_path(image)).read_bytes()).hexdigest(),
        "base_path": base,
        "target_path": target.target_path(image),
        "asm_path": target.info["asm"],
        "src_path": "ps2/src",
        "build_path": f"{build}/splat/{image}",
        "ld_script_path": f"{build}/splat/{image}.ld",
        "symbol_addrs_path": f"[{config}/{image}.symbols.txt]",
        "undefined_syms_auto_path": f"{build}/splat/{image}.undefined_syms.txt",
        "undefined_funcs_auto_path": f"{build}/splat/{image}.undefined_funcs.txt",
    }
    units = []
    for line in text.splitlines():
        m = YAML_SUB.match(line)
        if m and m.group(4) in UNIT_KINDS:
            units.append((source.address(image, int(m.group(2), 16)), m.group(5)))
    unit_end = {name: (units[i + 1][0] if i + 1 < len(units) else None)
                for i, (_a, name) in enumerate(units)}
    runs = [source.address(image, int(m.group(2), 16))
            for m in map(YAML_SUB.match, text.splitlines()) if m and m.group(4) == ".rodata"]
    unit_start = {name: a for a, name in units}
    rows = []
    for m in map(YAML_SUB.match, text.splitlines()):
        if m:
            vram = YAML_VRAM.search(m.group(3))
            rows.append(int(vram.group(2), 16) if vram else source.address(image, int(m.group(2), 16)))

    def datum(address):
        """Where a data row starting at `address` starts in the target."""
        moved = carry.anchors[image].get(address)
        if moved is None:
            moved = carry.datum(image, address)
        if moved is None:
            end = min([a for a in rows if a > address], default=address + 1)
            kept = sorted(carry.data[image][a] for a in carry.keys[image] if address <= a < end)
            moved = kept[0] if kept else None
        return moved

    out = []
    in_segment_header = False
    for line in text.splitlines():
        key = re.match(r"^(\s*)(\w+):\s*(.*)$", line)
        if key and key.group(2) in fields and key.group(1) in ("", "  "):
            out.append(f"{key.group(1)}{key.group(2)}: {fields[key.group(2)]}")
            continue
        if re.match(r"^\s*-\s*name:\s*" + image + r"\s*$", line):
            in_segment_header = True
        if in_segment_header and key and key.group(2) in ("start", "vram", "bss_size"):
            lo, hi = target.image_range(image)
            value = {"start": target.offset(image, lo),
                     "vram": lo,
                     "bss_size": hi - target.file_end(image)}[key.group(2)]
            out.append(f"{key.group(1)}{key.group(2)}: {value:#x}")
            continue
        if key and key.group(2) == "subsegments":
            in_segment_header = False
        m = YAML_SUB.match(line)
        if m:
            address = source.address(image, int(m.group(2), 16))
            kind, name = m.group(4), m.group(5)
            if kind in UNIT_KINDS:
                moved = carry.text(image, address)
                if moved is None:
                    end = unit_end[name]
                    starts = [carry.text(image, f["value"]) for f in source.functions(image)
                              if address <= f["value"] < (end or 1 << 32)]
                    starts = [s for s in starts if s is not None]
                    moved = min(starts) if starts else None
            elif kind == ".rodata":
                moved = carry.datum(image, address)
                ro = [(lo, hi) for n, _k, lo, hi in target.sections[image] if n == ".rodata"]
                if moved is not None and not any(lo <= moved < hi for lo, hi in ro):
                    moved = None
                if moved is None:
                    later = [a for a in runs if a > address]
                    end = min(later) if later else ro[0][1]
                    kept = sorted(carry.data[image][s["value"]] for s in source.syms
                                  if address <= s["value"] < end and s["value"] in carry.data[image]
                                  and s["shndx"] == source.shndx[image])
                    moved = kept[0] if kept else None
                if moved is None and not rodata_refs(carry, image, name, unit_start, unit_end):
                    problems.append(f"{image}.yaml: {name} has no constants in {target.name}; dropped")
                    continue
            else:
                moved = datum(address)
            if moved is None:
                problems.append(f"{image}.yaml: {kind} {name} at {address:#x} has no counterpart")
                moved = address

            def vram(v):
                moved = datum(int(v.group(2), 16))
                if moved is None:
                    problems.append(f"{image}.yaml: {name} at vram {v.group(2)} has no counterpart")
                    moved = int(v.group(2), 16)
                return v.group(1) + hex_like(v.group(2), moved)

            rest = YAML_VRAM.sub(vram, m.group(3))
            out.append(m.group(1) + hex_like(m.group(2), target.offset(image, moved)) + rest)
            continue
        m = YAML_END.match(line)
        if m:
            address = source.address(image, int(m.group(2), 16))
            moved = carry.anchors[image].get(address, address)
            out.append(m.group(1) + hex_like(m.group(2), target.offset(image, moved)) + m.group(3))
            continue
        out.append(line)
    starts = [int(m.group(2), 16) for m in map(YAML_SUB.match, out) if m]
    for a, b in zip(starts, starts[1:]):
        if b < a:
            problems.append(f"{image}.yaml: subsegments out of order at {b:#x}")
    return "\n".join(out) + "\n"


def rodata_refs(carry, image, name, unit_start, unit_end):
    """Whether the target's copy of a unit loads anything from .rodata."""
    target = carry.target
    starts = [carry.text(image, f["value"]) for f in carry.source.functions(image)
              if unit_start[name] <= f["value"] < (unit_end[name] or 1 << 32)]
    starts = [s for s in starts if s is not None]
    if not starts:
        return False
    by_start = {f["value"]: f for f in target.functions(image)}
    ro = [(lo, hi) for n, _k, lo, hi in target.sections[image] if n in (".rodata", ".rdata")]
    for start in starts:
        f = by_start.get(start)
        if f is None:
            continue
        for address in range(start, start + f["size"], 4):
            for _kind, _name, value in target.rel.get(image, {}).get(address, ()):
                if any(lo <= value < hi for lo, hi in ro):
                    return True
    return False


LCF_BLOCK = re.compile(r"^\s*\.(title|dun|main)\s*:")
LCF_ASSIGN = re.compile(r"^(\s*)(\w+)(\s*=\s*)(0x[0-9a-fA-F]+)(;\s*(?://\s*(\S+)\s*)?)$")
LCF_TEXT = re.compile(r"\(\s*\.[td]?text\s*\)")
HEX = re.compile(r"0x[0-9a-fA-F]{8}\b")


def unit_text(carry, image, address, starts):
    """Where a unit whose first function the target lacks starts in the target."""
    later = [a for a in starts if a > address]
    end = min(later) if later else carry.source.image_range(image)[1]
    moved = [carry.text(image, f["value"]) for f in carry.source.functions(image)
             if address <= f["value"] < end]
    moved = [m for m in moved if m is not None]
    return min(moved) if moved else None


def carry_assignment(carry, name, address, noted, problems):
    """Where a symbol the linker script defines by address stands in the target.

    An overlay entry point main calls by address keeps the name its source
    spells, and notes retail's name for the function, which is found in the
    target by that name. A symbol retail's own table defines takes the
    target's value. Any other address inside main -- a name retail reaches as
    an offset into a datum -- moves with the data around it.
    """
    source, target = carry.source, carry.target

    def values(retail, wanted, kind=None):
        return {s["value"] for s in retail.syms
                if s["name"] == wanted and (kind is None or s["type"] == kind)}

    if noted:
        found = values(target, noted, STT_FUNC)
        if address in values(source, noted, STT_FUNC) and len(found) == 1:
            return found.pop()
        problems.append(f"lcf: {name} ({noted}) has no single counterpart")
        return address
    if address in values(source, name):
        found = values(target, name)
        if len(found) == 1:
            return found.pop()
        problems.append(f"lcf: {name} has no single counterpart")
        return address
    lo, hi = source.image_range("main")
    if not lo <= address < hi:
        return address
    moved = carry.datum("main", address)
    if moved is None:
        problems.append(f"lcf: {name} = {address:#x} has no counterpart")
        return address
    return moved


def carry_lcf(carry, text, problems):
    source, target = carry.source, carry.target
    starts = defaultdict(list)
    image = None
    for line in text.splitlines():
        block = LCF_BLOCK.match(line)
        if block:
            image = block.group(1)
        if image and "//" in line and LCF_TEXT.search(line.split("//", 1)[0]):
            starts[image] += [int(t, 16) for t in HEX.findall(line.split("//", 1)[1])]
    image = None
    out = []
    for line in text.splitlines():
        block = LCF_BLOCK.match(line)
        if block:
            image = block.group(1)
        if "ORIGIN" in line and "0x" in line:
            line = HEX.sub(lambda t: hex_like(t.group(0), target.images["title"][0])
                           if int(t.group(0), 16) == source.images["title"][0] else t.group(0), line)
            out.append(line)
            continue
        gp = re.match(r"^(\s*_gp\s*=\s*)(0x[0-9a-fA-F]+)(;.*)$", line)
        if gp:
            out.append(gp.group(1) + hex_like(gp.group(2), target.gp) + gp.group(3))
            continue
        assign = LCF_ASSIGN.match(line)
        if assign:
            moved = carry_assignment(carry, assign.group(2), int(assign.group(4), 16),
                                     assign.group(6), problems)
            out.append(assign.group(1) + assign.group(2) + assign.group(3)
                       + hex_like(assign.group(4), moved) + assign.group(5))
            continue
        if "//" not in line or image is None:
            out.append(line)
            continue
        code, comment = line.split("//", 1)

        def move(token):
            address = int(token.group(0), 16)
            owner = image
            if owner == "main" and address >= source.image_range("main")[1]:
                return token.group(0)
            moved = None
            if LCF_TEXT.search(code) or comment.lstrip().startswith("@ORDER"):
                moved = carry.text(owner, address)
                if moved is None:
                    moved = unit_text(carry, owner, address, starts[owner])
            if moved is None:
                moved = carry.datum(owner, address)
            if moved is None:
                problems.append(f"lcf: {token.group(0)} ({owner}) has no counterpart")
                return token.group(0)
            return hex_like(token.group(0), moved)

        out.append(code + "//" + HEX.sub(move, comment))
    return "\n".join(out) + "\n"


STATIC = re.compile(r"^(.*)\$\d+$")


def static_family(name):
    """The name a function-local static is declared by, without the compiler's
    `$N` number."""
    m = STATIC.match(name)
    return m.group(1) if m else None


class Statics:
    """Where a function-local static NTSC's retail names `name$M` went.

    The compiler numbers a unit's statics off one counter, so the same static
    carries another number in a release whose unit emits a different set of
    names before it, and a name alone can pair two different statics. It is
    found through the function that owns it -- the target's copy of that
    function refers to as many statics of the name, in the same order -- and a
    static no function refers to by the data around it.
    """

    def __init__(self, carry):
        self.carry = carry
        self.source_names = carry.source_names
        self.target_names = carry.target_names
        self.by_name = {}
        for s in carry.source.syms:
            if s["idx"] in self.source_names:
                self.by_name.setdefault(self.source_names[s["idx"]], s)
        self.functions = {}
        for retail in (carry.source, carry.target):
            for image in IMAGES:
                rows = sorted((f["value"], f["value"] + f["size"]) for f in retail.functions(image))
                self.functions[(retail.name, image)] = ([a for a, _e in rows], rows)

    def _spelled(self, retail, names, raw, value, image):
        for s in retail.syms:
            if s["name"] == raw and s["value"] == value and retail.image_of(s) == image:
                return names[s["idx"]]
        return None

    def _referrers(self, retail, image, value):
        """The start of every function that refers to `value`."""
        starts, rows = self.functions[(retail.name, image)]
        out = set()
        for address, entries in retail.rel.get(image, {}).items():
            if not any(v == value for _k, _n, v in entries):
                continue
            i = bisect.bisect_right(starts, address) - 1
            if i >= 0 and address < rows[i][1]:
                out.add(rows[i][0])
        return out

    def _referenced(self, retail, image, start, family):
        """{(raw name, value)} of every static of `family` a function refers to."""
        starts, rows = self.functions[(retail.name, image)]
        end = rows[bisect.bisect_left(starts, start)][1]
        out = set()
        for address in range(start, end, 4):
            for _k, name, value in retail.rel.get(image, {}).get(address, ()):
                if static_family(name) == family:
                    out.add((name, value))
        return out

    def name(self, retail_name):
        s = self.by_name.get(retail_name)
        if s is None:
            return None
        carry, source, target = self.carry, self.carry.source, self.carry.target
        image = source.image_of(s)
        family = static_family(s["name"])
        if image is None or family is None:
            return None
        # A function with several statics of one name declares them in the
        # order both releases lay them out. Main's small data holds the
        # overlays' statics too, so the owner can be a function of any image.
        found, owned = set(), False
        for user in IMAGES:
            for start in self._referrers(source, user, s["value"]):
                owned = True
                moved = carry.text(user, start)
                if moved is None:
                    continue
                mine = sorted(self._referenced(source, user, start, family), key=lambda r: r[1])
                theirs = sorted(self._referenced(target, user, moved, family), key=lambda r: r[1])
                if len(mine) == len(theirs):
                    found.add(theirs[mine.index((s["name"], s["value"]))])
        if len(found) == 1:
            raw, value = found.pop()
            return self._spelled(target, self.target_names, raw, value, image)
        if owned:
            return None
        # A static no function refers to moves with the data around it.
        moved = carry.datum(image, s["value"])
        for t in target.syms:
            if (moved is not None and t["value"] == moved and target.image_of(t) == image
                    and static_family(t["name"]) == family):
                return self.target_names[t["idx"]]
        return None


def carry_fixups(carry, fixups, problems):
    def image_of(source):
        for image in ("title", "dun"):
            if source.startswith(f"ps2/src/{image}/"):
                return image
        return "main"

    retail_names = {}
    for s in carry.source.syms:
        if s["idx"] in carry.source_names:
            retail_names.setdefault(carry.source_names[s["idx"]], s)

    def move(value, image):
        if isinstance(value, str):
            if value not in retail_names:
                return value
            moved = carry.name(image, value)
            if moved is None:
                problems.append(f"object_fixups: {value} ({image}) has no counterpart; dropped")
            return moved
        if isinstance(value, list):
            return [m for m in (move(v, image) for v in value) if m is not None]
        if isinstance(value, dict):
            return {k: m for k, m in ((k, move(v, image)) for k, v in value.items()) if m is not None}
        return value

    names = {}
    for retail in (carry.source, carry.target):
        spelling = spelled(retail)
        names[retail] = {}
        for s in retail.syms:
            if s["idx"] in spelling:
                names[retail].setdefault(spelling[s["idx"]], s)

    def contents(retail, image, name):
        """A datum's bytes, each word a relocation fills masked."""
        s = names[retail].get(name)
        if s is None or not s["size"]:
            return None
        owner = retail.image_of(s) or image
        base, blob = retail.images[owner]
        data = bytearray(blob[s["value"] - base:s["value"] - base + s["size"]])
        rel = retail.rel.get(owner, {})
        for address in range(s["value"], s["value"] + s["size"], 4):
            if address in rel:
                offset = address - s["value"]
                data[offset:offset + 4] = b"\0" * len(data[offset:offset + 4])
        return bytes(data)

    def exported(value, image):
        """An exported constant keeps its export in the target; one whose bytes
        differ there is named, since the unit's PAL source has to hold them."""
        moved = move(value, image)
        if moved is not None and contents(carry.source, image, value) != contents(carry.target, image, moved):
            problems.append(f"object_fixups: {value} ({image}) holds something else in "
                            f"{carry.target.name} as {moved}")
        return moved

    statics = Statics(carry)

    # Retail's names are carried over; the compiler's are the same in both
    # releases, which compile the same source. A `sections` or
    # `globalize_symbols` entry is a compiled name unless the unit exports it.
    retail_keys = ("rodata_exports", "data_runs", "export_constants_shared",
                   "import_constants_shared")
    out = {}
    for source, rows in fixups.items():
        image = image_of(source)
        exports = set(rows.get("symbols", {}).values()) | set(rows.get("rodata_exports", []))
        moved = {}
        for key, value in rows.items():
            if key == "symbols":
                moved[key] = move(value, image)
            elif key == "rodata_exports":
                moved[key] = [m for m in (exported(v, image) for v in value) if m is not None]
            elif key == "statics":
                kept = {}
                for compiled, retail_name in value.items():
                    m = statics.name(retail_name)
                    if m is None:
                        problems.append(f"object_fixups: {source} static {retail_name} has no "
                                        f"counterpart; dropped")
                    else:
                        kept[compiled] = m
                moved[key] = kept
            elif key in retail_keys:
                moved[key] = move(value, image)
            elif key == "sections":
                moved[key] = {k: [m for m in (move(v, image) if v in exports else v for v in listed)
                                  if m is not None]
                              for k, listed in value.items()}
            elif key == "globalize_symbols":
                moved[key] = [m for m in (move(v, image) if v in exports else v for v in value)
                              if m is not None]
            else:
                moved[key] = value
        out[source] = moved
    return json.dumps(out, indent=2) + "\n"


def write(path, text, check, stale):
    path = Path(path)
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="compare instead of writing")
    mode.add_argument("--overwrite", action="store_true",
                      help="rewrite the carried yaml, linker script and fixups")
    args = ap.parse_args()

    ntsc = region.paths(region.NTSC)
    target = Retail(region.NAME)
    source = target if region.NAME == region.NTSC else Retail(region.NTSC)
    config = Path(target.info["config"])
    ntsc_config = Path(ntsc["config"])
    carry = Carry(source, target)
    problems, stale = [], []

    # The symbol lists are always the images' own. The carried files are
    # checked only on NTSC, where carrying is the identity: another release's
    # are maintained by hand once written.
    carried = region.NAME != region.NTSC and not args.check
    def written(path, text):
        if region.NAME == region.NTSC:
            if args.check:
                write(path, text, True, stale)
        elif carried and (args.overwrite or not Path(path).exists()):
            write(path, text, False, stale)

    for image in IMAGES:
        write(config / f"{image}.symbols.txt", symbol_list(target, image), args.check, stale)
        yaml = (ntsc_config / f"{image}.yaml").read_text(encoding="utf-8")
        written(config / f"{image}.yaml", carry_yaml(carry, image, yaml, problems))
    lcf = Path(ntsc["lcf"]).read_text(encoding="utf-8")
    written(target.info["lcf"], carry_lcf(carry, lcf, problems))
    if region.NAME != region.NTSC:
        fixups = json.loads((ntsc_config / "object_fixups.json").read_text(encoding="utf-8"))
        written(config / "object_fixups.json", carry_fixups(carry, fixups, problems))

    for problem in problems:
        print(f"splat_config: {problem}", file=sys.stderr)
    if args.check:
        for path in stale:
            print(f"splat_config: {path} differs from what would be written", file=sys.stderr)
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
