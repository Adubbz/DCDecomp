#!/usr/bin/env python3
"""Turn one function's reference dump into an MWCC `asm` function body.

    gen_asm_body.py <ref.s> <symbol> <out.inc>

A function that does not yet compile to retail's bytes is normally supplied by
its own .s object instead. That works everywhere except inside a translation
unit whose other functions retail placed around it: MWCC emits a TU's functions
as one contiguous .text, so a hole in the middle cannot be filled by a separate
object. src/dngstatusdata.cpp is that case -- four unmatched functions sit
between matched ones.

So the function stays in the TU, with retail's own instructions as its body.
MWCC assembles an `asm` body verbatim, which makes it byte-identical to the .s
it replaces; the C++ that does not match yet is kept beside it, compiled out,
for whoever picks the register allocation back up.

Two things have to change on the way in. The dumps carry
`/* fileoff vaddr word */` comments, and their branch labels are spelled
`.L0012C700` -- MWCC's inline assembler reads a leading dot as the start of a
directive and rejects the label outright, so the dot is dropped.
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# `.L001BE57C` -> `L001BE57C`, in both the definition and the branches.
LABEL_RE = re.compile(r'\.L([0-9A-Fa-f]{6,8})\b')

# MWCC's inline assembler has no %hi/%lo, so the address pair the dumps spell
# out becomes the `la` macro, which expands right back to the same two
# instructions and relocations.
HI_RE = re.compile(r'^\s*lui\s+(\$\d+),\s*%hi\(([^)]+)\)\s*$')
LO_RE = re.compile(r'^\s*addiu\s+(\$\d+),\s*(\$\d+),\s*%lo\(([^)]+)\)\s*$')


def body(ref, symbol):
    """The instruction and label lines of one function, in MWCC asm syntax."""
    lines, inside = [], False
    with open(os.path.join(REPO, ref), encoding='utf-8') as f:
        for line in f:
            if line.startswith('glabel '):
                inside = line.split()[1].strip() == symbol
                continue
            if not inside:
                continue
            label = re.match(r'\s*(\.L[0-9A-Fa-f]+:)\s*$', line)
            if label:
                lines.append(LABEL_RE.sub(r'L\1', label.group(1)))
                continue
            insn = re.match(r'/\*[^*]*\*/\s+(.*?)\s*$', line)
            if insn and insn.group(1):
                lines.append('    ' + LABEL_RE.sub(r'L\1', insn.group(1)))
    if not lines:
        raise SystemExit('gen_asm_body: %s is not in %s' % (symbol, ref))
    return fold_addresses(lines)


def fold_addresses(lines):
    """Collapse each `lui %hi` / `addiu %lo` pair into one `la`."""
    out, i = [], 0
    while i < len(lines):
        hi = HI_RE.match(lines[i])
        lo = LO_RE.match(lines[i + 1]) if hi and i + 1 < len(lines) else None
        if lo and lo.group(2) == hi.group(1) and lo.group(3) == hi.group(2):
            out.append('    la          %s, %s' % (lo.group(1), lo.group(3)))
            i += 2
            continue
        out.append(lines[i])
        i += 1
    return out


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    ref, symbol, out = sys.argv[1:]
    lines = body(ref, symbol)

    path = os.path.join(REPO, out)
    os.makedirs(os.path.dirname(path), exist_ok=True)

    text = ('/* %s, as retail assembled it. Generated by\n'
            ' * scripts/build/gen_asm_body.py from %s -- do not edit.\n'
            ' * See that script for why this function is not C++ yet. */\n'
            % (symbol, ref)) + '\n'.join(lines) + '\n'

    # Only when it actually changed. This runs at configure time, and the
    # sources that include these bodies are compiled against their timestamps:
    # rewriting an identical file would recompile dngstatusdata.cpp and relink
    # on every configure, which is every build and every asm-differ rebuild.
    if os.path.exists(path):
        with open(path, encoding='utf-8') as f:
            if f.read() == text:
                return

    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %s (%d lines)' % (out, len(lines)))


if __name__ == '__main__':
    main()
