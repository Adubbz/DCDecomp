constexpr std::uint8_t kBackdropAlpha = 0x60;

gfx::Vertex2D Vertex(float x, float y, std::uint8_t grey, std::uint8_t alpha) {
    return gfx::Vertex2D{
        x, y, 0.0f, 0.0f, 0.0f, {grey, grey, grey, alpha}
    };
}

