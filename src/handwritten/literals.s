# MWLD gathered every unit's float and double constants here. It did not
# merge them, and retail's toolchain emitted the same constant more than once
# within one function, which this compiler never does, so the pool cannot be
# rebuilt from the objects. scripts/build/literals.py binds each constant a
# compiled unit loads to the entry retail loads it from, by address, which
# is why the words below carry no labels of their own.

